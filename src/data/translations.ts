export function getTranslatedKands(lang: Language): Kand[] {
  if (lang === 'Hindi') {
    return kands.map(k => ({
      ...k,
      ...kandTranslations[k.id],
      themes: k.themes ? k.themes.map((t, idx) => ({
        title: kandTranslations[k.id]?.themes?.[idx]?.title || t.title,
        description: kandTranslations[k.id]?.themes?.[idx]?.description || t.description
      })) : undefined,
      verses: k.verses // keep original verses & transliteration
    }));
  }
  return kands;
}

