export function getTranslatedQuizzes(lang: Language): Quiz[] {
  if (lang === 'Hindi') {
    return quizzes.map(q => {
      const transQuestions = q.questions.map(question => {
        const tr = quizTranslations[question.id];
        if (tr) {
          return {
            ...question,
            question: tr.question,
            options: tr.options,
            explanation: tr.explanation
          };
        }
        return question;
      });
      return {
        ...q,
        questions: transQuestions
      };
    });
  }
  return quizzes;
}

