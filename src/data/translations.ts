// NATIVE TEXT-TO-SPEECH (TTS) AUDIO GUIDE
// ----------------------------------------------------
export function speakText(text: string, lang: Language) {
  if (typeof window === 'undefined' || !window.speechSynthesis) return;

  // Cancel any active speech synthesis
  window.speechSynthesis.cancel();

  // Create new utterance
  const utterance = new SpeechSynthesisUtterance(text);
  utterance.lang = lang === 'Hindi' ? 'hi-IN' : 'en-US';
  utterance.rate = lang === 'Hindi' ? 0.88 : 0.95; // slightly slower for better temple ambiance clarity

  // Fetch native system voices
  const voices = window.speechSynthesis.getVoices();
  
  // Try to find a native Hindi or English voice
  const voice = voices.find(v => v.lang.toLowerCase().startsWith(lang === 'Hindi' ? 'hi' : 'en'));
  if (voice) {
    utterance.voice = voice;
  }

  window.speechSynthesis.speak(utterance);
}

export function getTranslatedVersions(lang: Language): VersionDetail[] {
  if (lang === 'Hindi') {
    return versions.map(v => {
      const trans = versionTranslations[v.name];
      if (trans) {
        return {
          ...v,
          name: trans.name,
          focus: trans.focus,
          differences: v.differences.map((diff, index) => {
            const transDiff = trans.differences[index];
            if (transDiff) {
              return {
                topic: transDiff.topic,
                narrative: transDiff.narrative
              };
            }
            return diff;
          })
        };
      }
      return v;
    });
  }
  return versions;
}
